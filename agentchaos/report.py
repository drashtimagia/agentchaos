"""Generate a self-contained single-file HTML report from benchmark results."""

from __future__ import annotations

import html
from pathlib import Path

from agentchaos.core.models import Run
from agentchaos.execution import CLEAN
from agentchaos.scoring.score import ClassSummary, summarize

_CSS = """
body{font-family:system-ui,sans-serif;margin:0;padding:1.5rem;background:#f8f9fa;color:#212529}
h1{font-size:1.4rem;margin-bottom:.25rem}
.meta{color:#6c757d;font-size:.85rem;margin-bottom:2rem}
h2{font-size:1.1rem;margin:2rem 0 .5rem;border-bottom:1px solid #dee2e6;padding-bottom:.3rem}
table{border-collapse:collapse;width:100%;font-size:.88rem;margin-bottom:1.5rem}
th,td{padding:.45rem .7rem;text-align:right;border:1px solid #dee2e6}
th{background:#e9ecef;font-weight:600}
td:first-child,th:first-child{text-align:left}
tr.clean td{background:#f1f8e9}
tr.best td{background:#e8f5e9}
tr.worst td{background:#fff3e0}
.ok{color:#2e7d32}.warn{color:#f57c00}.bad{color:#c62828}
footer{margin-top:3rem;font-size:.8rem;color:#adb5bd}
"""

_HTML_TMPL = """\
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>AgentChaos Benchmark Report</title>
<style>{css}</style>
</head>
<body>
<h1>AgentChaos Benchmark Report</h1>
<p class="meta">{meta}</p>
{body}
<footer>Generated by <a href="https://github.com/drashtimagia/agentchaos">AgentChaos</a></footer>
</body>
</html>
"""


def _pct(v: float) -> str:
    return f"{v:.0%}"


def _ci(lo: float, hi: float) -> str:
    return f"{lo:.0%}&ndash;{hi:.0%}"


def _deg(v: float | None) -> str:
    if v is None:
        return "&mdash;"
    cls = "ok" if v >= 0.9 else ("warn" if v >= 0.6 else "bad")
    return f'<span class="{cls}">{v:.2f}</span>'


def _sr(v: float | None) -> str:
    return "&mdash;" if v is None else _pct(v)


def _scenario_table(agent: str, summaries: list[ClassSummary]) -> str:
    rows = []
    best_fc = max(
        (s for s in summaries if s.fault_class != CLEAN),
        key=lambda s: s.success_rate,
        default=None,
    )
    worst_fc = min(
        (s for s in summaries if s.fault_class != CLEAN),
        key=lambda s: s.success_rate,
        default=None,
    )

    for s in summaries:
        lo, hi = s.success_ci
        row_cls = ""
        if s.fault_class == CLEAN:
            row_cls = "clean"
        elif best_fc and s.fault_class == best_fc.fault_class:
            row_cls = "best"
        elif worst_fc and s.fault_class == worst_fc.fault_class:
            row_cls = "worst"

        rows.append(
            f'<tr class="{row_cls}">'
            f"<td>{html.escape(s.fault_class)}</td>"
            f"<td>{s.successes}/{s.n} ({_pct(s.success_rate)})</td>"
            f"<td>{_ci(lo, hi)}</td>"
            f"<td>{_deg(s.degradation)}</td>"
            f"<td>{_pct(s.safety_violation_rate)}</td>"
            f"<td>{_sr(s.surrender_rate)}</td>"
            f"<td>{s.mean_calls:.1f}</td>"
            f"<td>{s.mean_faults:.1f}</td>"
            "</tr>"
        )

    return (
        f"<p><strong>Agent:</strong> {html.escape(agent)}</p>"
        "<table>"
        "<tr><th>Class</th><th>Success</th><th>95% CI</th><th>vs clean</th>"
        "<th>Unsafe</th><th>Surrender</th><th>Calls</th><th>Faults</th></tr>"
        + "".join(rows)
        + "</table>"
    )


def render(
    bench_results: dict[str, dict[str, list[Run]]],
    *,
    title_meta: str = "",
) -> str:
    """Return a self-contained HTML string.

    ``bench_results`` maps scenario_name -> agent_name -> list[Run].
    """
    sections: list[str] = []
    for scenario_name, by_agent in bench_results.items():
        sections.append(f"<h2>{html.escape(scenario_name)}</h2>")
        for agent_name, runs in by_agent.items():
            summaries = summarize(runs)
            sections.append(_scenario_table(agent_name, summaries))

    body = "\n".join(sections) or "<p>No results.</p>"
    return _HTML_TMPL.format(css=_CSS, meta=html.escape(title_meta), body=body)


def write_report(
    bench_results: dict[str, dict[str, list[Run]]],
    path: Path,
    *,
    title_meta: str = "",
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(bench_results, title_meta=title_meta), encoding="utf-8")
